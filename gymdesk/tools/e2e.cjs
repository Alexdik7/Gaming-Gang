// Ende-zu-Ende-Test: node gymdesk/tools/e2e.cjs  (Server: cd gymdesk && python3 -m http.server 8061)
const { chromium } = require('playwright');
const URL = process.env.GD_URL || 'http://localhost:8061/';
const SHOTS = process.env.GD_SHOTS || '';
const ok = (c, m) => { if (!c) throw new Error('FEHLER: ' + m); console.log('✓', m); };
(async () => {
  const b = await chromium.launch();
  const page = await b.newPage({ viewport: { width: 1180, height: 820 }, hasTouch: true });
  const errs = [];
  page.on('pageerror', (e) => errs.push(e.message));
  page.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
  const shot = async (n) => SHOTS && page.screenshot({ path: `${SHOTS}/${n}.png` });
  await page.goto(URL);
  await page.fill('#su-pw', 'Test1234'); await page.fill('#su-pw2', 'Test1234');
  await page.click('button[type=submit]');
  await page.waitForSelector('.kpis', { timeout: 30000 });
  ok(await page.locator('.kpi').count() === 5, 'Dashboard mit 5 Kennzahlen');
  await shot('01-dashboard');
  await page.click('.kpi.amber'); await page.waitForSelector('.rtable');
  ok((await page.locator('.rtable tbody tr').count()) >= 1, 'Kachel "Laufen aus" führt zu gefilterter Liste');
  await page.goto(URL + '#/mitglieder'); await page.waitForSelector('.rtable tbody tr');
  ok(await page.locator('.rtable tbody tr').count() === 10, '10 Testmitglieder');
  await page.fill('.search-in', 'musterfrau'); ok(await page.locator('.rtable tbody tr').count() === 1, 'Suche nach Nachname');
  await page.fill('.search-in', 'M-00004'); ok(await page.locator('.rtable tbody tr').count() === 1, 'Suche nach Mitgliedsnummer');
  await page.fill('.search-in', ''); await shot('02-mitglieder');
  // Anmeldung
  await page.goto(URL + '#/anmeldung'); await page.waitForSelector('.step-card');
  await page.click('.step-foot .btn.primary');
  ok(await page.locator('.field.invalid').count() >= 8, 'Pflichtfelder werden am Feld gemeldet');
  await page.click('.seg button:has-text("Herr")');
  const fill = async (n, v) => page.fill(`[name=${n}]`, v);
  await fill('firstName', 'Neo'); await fill('lastName', 'Testkunde'); await fill('birthDate', '1995-05-05');
  await fill('street', 'Probeweg'); await fill('houseNo', '7a'); await fill('zip', '1234'); await fill('city', 'Musterstadt');
  await fill('phone', '0151 2222333'); await fill('email', 'neo@falsch');
  await page.click('.step-foot .btn.primary');
  ok(await page.locator('[data-field=zip].invalid').count() === 1 && await page.locator('[data-field=email].invalid').count() === 1, 'PLZ- und E-Mail-Prüfung');
  await fill('zip', '12345'); await fill('email', 'neo.testkunde@example.com');
  await shot('03-anmeldung-daten');
  await page.click('.step-foot .btn.primary');
  await page.click('.choice:has-text("Premium – 12 Monate")');
  await shot('04-mitgliedschaft');
  await page.click('.step-foot .btn.primary');
  await page.click('.choice:has-text("Getränke-Flat")'); await page.click('.choice:has-text("Sauna")');
  ok((await page.textContent('.aside-price b')).includes('67,70'), 'Preis automatisch berechnet (49,90 + 9,90 + 7,90 = 67,70 €)');
  await shot('05-leistungen');
  await page.click('.step-foot .btn.primary');
  await fill('iban', 'DE89 3704 0044 0532 0130 01');
  await page.click('.step-foot .btn.primary');
  ok(await page.locator('[data-field=iban].invalid').count() === 1, 'Falsche IBAN wird erkannt');
  await fill('iban', 'DE89 3704 0044 0532 0130 00');
  await page.click('.step-foot .btn.primary');
  await page.click('.step-foot .btn.primary');
  ok(await page.locator('.consent.invalid').count() === 4, 'Pflicht-Zustimmungen erforderlich');
  for (const k of ['agb', 'hausordnung', 'datenschutz', 'sepa', 'werbung']) await page.check(`[data-field=consent_${k}] input`);
  await shot('06-einverstaendnis');
  await page.click('.step-foot .btn.primary');
  ok(await page.locator('.summary').count() === 1, 'Zusammenfassung');
  await page.click('.step-foot .btn.primary');
  await page.click('.step-foot .btn.primary');
  ok(await page.locator('[data-field=signature] .err').textContent() !== '', 'Ohne Unterschrift kein Weiter');
  const box = await page.locator('.sig-canvas').boundingBox();
  await page.mouse.move(box.x + 80, box.y + 160); await page.mouse.down();
  for (let i = 0; i < 40; i++) await page.mouse.move(box.x + 80 + i * 14, box.y + 160 + Math.sin(i / 2) * 40, { steps: 2 });
  await page.mouse.up();
  await shot('07-unterschrift');
  await page.click('button:has-text("Unterschrift bestätigen")');
  ok(await page.locator('.sig-preview img').count() === 1, 'Unterschrift-Vorschau');
  await page.click('.step-foot .btn.primary');
  await shot('08-abschluss');
  await page.click('.btn.success');
  await page.waitForSelector('.success-box');
  ok((await page.textContent('.success-box h2')).includes('Mitgliedschaft erfolgreich abgeschlossen.'), 'Erfolgsmeldung');
  await shot('09-bestaetigung');
  await page.click('a:has-text("Mitglied öffnen")'); await page.waitForSelector('.profile-head');
  ok((await page.textContent('.profile-head')).includes('Neo Testkunde'), 'Kundenmaske öffnet');
  ok((await page.textContent('.iban-row')).includes('••••'), 'IBAN maskiert');
  await shot('10-kundenmaske');
  await page.click('a:has-text("Original-Formular öffnen")'); await page.waitForSelector('.notice.ok');
  ok((await page.textContent('.notice')).includes('Original unverändert'), 'Formular schreibgeschützt + Prüfsumme gültig');
  await shot('11-formular');
  // Angebot
  await page.goto(URL + '#/angebote/neu'); await page.waitForSelector('.count-box');
  await fill('name', 'Test-Angebot'); await fill('subject', 'Hallo {{vorname}}');
  await page.waitForTimeout(300);
  const cnt = await page.textContent('.count-box b');
  ok(/wird an \d+ Mitglied/.test(cnt), 'Empfängeranzahl: ' + cnt);
  ok((await page.textContent('.mail-meta')).match(/Hallo \w+/), 'Platzhalter in der Vorschau ersetzt');
  await shot('12-angebot');
  await page.click('button:has-text("Jetzt versenden")'); await page.click('.modal-foot .btn.primary');
  await page.waitForSelector('text=Postausgang');
  ok((await page.locator('.list li').count()) >= 1, 'Mock-Versand im Postausgang');
  for (const t of ['gym', 'plans', 'addons', 'legal', 'mail', 'security']) { await page.goto(URL + '#/einstellungen?tab=' + t); await page.waitForSelector('.tabs'); }
  ok(true, 'Alle Einstellungs-Tabs laden');
  await page.goto(URL + '#/einstellungen?tab=plans'); await page.waitForSelector('.list'); await shot('13-einstellungen');
  // Entwurf + Verlassen-Schutz
  await page.goto(URL + '#/anmeldung'); await page.waitForSelector('.step-card');
  await fill('firstName', 'Entwurf'); await page.waitForTimeout(800);
  await page.click('[data-nav=mitglieder] >> nth=0');
  await page.waitForSelector('.modal', { timeout: 3000 }).catch(() => {});
  ok(await page.locator('.modal').count() === 1, 'Warnung beim Verlassen');
  await page.click('.modal-foot .btn.danger'); await page.waitForSelector('.rtable');
  await page.goto(URL + '#/anmeldung'); await page.waitForSelector('.notice');
  ok((await page.textContent('.notice')).includes('Entwurf'), 'Entwurf wird angeboten');
  // Sperre
  await page.click('button:has-text("Sperren")'); await page.waitForSelector('#lk-pw');
  await page.fill('#lk-pw', 'falsch123'); await page.click('button[type=submit]'); await page.waitForTimeout(1500);
  ok((await page.textContent('.err')).includes('nicht richtig'), 'Falsches Passwort abgelehnt');
  await page.fill('#lk-pw', 'Test1234'); await page.click('button[type=submit]'); await page.waitForSelector('.main');
  ok(true, 'Entsperren');
  // Verschlüsselung prüfen
  const raw = await page.evaluate(() => new Promise((res) => { const r = indexedDB.open('gymdesk'); r.onsuccess = () => { const q = r.result.transaction('members').objectStore('members').getAll(); q.onsuccess = () => res(JSON.stringify(q.result.map((x) => Object.keys(x)))); }; }));
  ok(!raw.includes('firstName'), 'Mitgliedsdaten liegen verschlüsselt in IndexedDB');
  // Handy + iPad hoch
  await page.setViewportSize({ width: 820, height: 1180 }); await page.goto(URL + '#/mitglieder'); await page.waitForSelector('.rtable'); await shot('14-ipad-hoch');
  await page.setViewportSize({ width: 390, height: 844 }); await page.goto(URL + '#/dashboard'); await page.waitForSelector('.kpis'); await shot('15-iphone');
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  ok(!overflow, 'Kein horizontales Scrollen am Handy');
  ok(errs.length === 0, 'Keine Konsolenfehler ' + errs.join(' | '));
  await b.close();
})().catch((e) => { console.error(e.message); process.exit(1); });
